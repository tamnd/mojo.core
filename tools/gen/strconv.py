#!/usr/bin/env python3
"""Emit the number tables `core.strconv` needs for floating point.

Three tables, none of which anybody should be reading:

`_POW10_HI` and `_POW10_LO` are the 128-bit mantissas of every power of ten
from 1e-348 to 1e347, normalised so the top bit is set. Eisel-Lemire parsing,
Dragonbox formatting and the fixed precision formatter all multiply by one of
these instead of doing decimal arithmetic. Go generates the same numbers with
`pow10gen.go` and checks the result in; this is that program in Python, and it
uses exact rational arithmetic for the same reason Go uses `math/big`, which is
that 5^23 is already too big for a float to hold exactly.

`_DIV5_INV` and `_DIV5_MAX` answer whether a mantissa is divisible by a power
of five, in a multiplication and a comparison rather than a division.

`_CHEAT_DELTA` and the digits beside it say how many decimal digits a binary
left shift adds. The cutoff for a shift of k is the decimal expansion of 5^k,
and comparing the leading digits against it is what decides between the two
possible answers. Go writes these out by hand with a shell pipeline in a
comment; they are derived here instead, because a derivation can be checked.

Everything here is deterministic and depends on nothing outside Python.
"""

from __future__ import annotations

import sys
from fractions import Fraction
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

TABLES = "core/strconv/tables.mojo"

# Go's `pow10Min` and `pow10Max`. The range covers every exponent a float64
# can be written with, with enough either side for the intermediate values.
POW10_MIN = -348
POW10_MAX = 347

# Go's `maxShift`, which is `uintSize - 4`: a shift has to leave room for
# `9 << k` in a machine word, and every platform here has 64-bit words.
MAX_SHIFT = 60

# `divisiblePow5` only answers for 1 through 22, because 5^23 is already
# larger than the largest float64 mantissa.
DIV5_MAX_POWER = 22

MAX_UINT64 = (1 << 64) - 1

HEADER = '''"""Every number `core.strconv` needs and nobody needs to read.

Generated by `tools/gen/strconv.py`. Do not edit: change the generator and run
`pixi run gen`. `pixi run generated-check` fails on a diff.

Nothing here is public. `math.mojo` reads the powers of ten and the divisibility
table, `decimal.mojo` reads the shift cheat sheet, and that is the whole
audience.

The powers of ten are held as two arrays rather than one array of pairs so that
the high half, which is the one every caller wants, is contiguous. `10^e` is
`(hi, lo) / 2^128 * 2^exp` where `exp` comes out of arithmetic rather than a
table, so only the mantissas are stored.
"""
'''


def array(name: str, kind: str, values: list[int], hex_width: int = 0) -> str:
    """One `comptime` array, one value to a line.

    One to a line for the reason `tools/gen/unicode.py` does it: `mojo format`
    explodes any collection with a trailing comma, and generated code the
    formatter would rewrite fails `format-check` the first time anybody runs it.
    """
    if hex_width:
        rendered = [f"0x{v:0{hex_width}X}" for v in values]
    else:
        rendered = [str(v) for v in values]
    body = "".join(f"    {v},\n" for v in rendered)
    return f"comptime {name}: Array[{kind}, {len(values)}] = [\n{body}]\n"


def pow10_table() -> tuple[list[int], list[int]]:
    """The high and low halves of the mantissa of every power of ten.

    Go's `pow10gen.go`. The value is scaled by powers of two until it lands in
    `[2^127, 2^128)`, so the top bit is always set and there is no implicit
    leading one, and then truncated towards zero. Truncation rather than
    rounding is what the algorithms above are proved against.
    """
    hi: list[int] = []
    lo: list[int] = []
    limit = Fraction(1 << 128)
    for e in range(POW10_MIN, POW10_MAX + 1):
        r = Fraction(10) ** e
        while r < limit:
            r *= 2
        while r >= limit:
            r /= 2
        d = r.numerator // r.denominator
        hi.append(d >> 64)
        lo.append(d & MAX_UINT64)
    return hi, lo


def div5_table() -> tuple[list[int], list[int]]:
    """For each power of five, its inverse modulo 2^64 and the largest multiple.

    `x` is divisible by `5^p` exactly when `x * inverse <= maxUint64 / 5^p`,
    because the inverse maps the multiples of `5^p` onto the bottom of the
    range and everything else above it. Go's `div5Tab`, computed here rather
    than written down.
    """
    inverses = []
    maxima = []
    for p in range(1, DIV5_MAX_POWER + 1):
        power = 5**p
        inverses.append(pow(power, -1, 1 << 64))
        maxima.append(MAX_UINT64 // power)
    return inverses, maxima


def left_cheats() -> tuple[list[int], list[int], list[str]]:
    """How many digits a left shift adds, and the prefix that decides.

    Go's `leftcheats`. Shifting left by `k` multiplies by `2^k`, which adds
    either `delta` or `delta - 1` digits: `delta` when the leading digits are at
    least `5^k`, one fewer when they are below it. `delta` is the digit count of
    `2^k`, which is exact integer arithmetic rather than the floating point
    `log10` in the comment beside Go's table.
    """
    deltas = [0]
    cutoffs = [""]
    for k in range(1, MAX_SHIFT + 1):
        deltas.append(len(str(2**k)))
        cutoffs.append(str(5**k))
    starts = [0]
    for cutoff in cutoffs:
        starts.append(starts[-1] + len(cutoff))
    return deltas, starts, cutoffs


def tables_file() -> str:
    hi, lo = pow10_table()
    inverses, maxima = div5_table()
    deltas, starts, cutoffs = left_cheats()

    out = [HEADER, "\n"]
    out.append(f"comptime _POW10_MIN = {POW10_MIN}\n")
    out.append('"""The smallest exponent `_pow10` answers for. Go\'s `pow10Min`."""\n\n')
    out.append(f"comptime _POW10_MAX = {POW10_MAX}\n")
    out.append('"""The largest exponent `_pow10` answers for. Go\'s `pow10Max`."""\n\n')
    out.append(array("_POW10_HI", "UInt64", hi, hex_width=16))
    out.append('"""The top 64 bits of the mantissa of `10^e`, for `e` from the\nminimum to the maximum, with the top bit always set."""\n\n')
    out.append(array("_POW10_LO", "UInt64", lo, hex_width=16))
    out.append('"""The bottom 64 bits of the same mantissas."""\n\n')
    out.append(array("_DIV5_INV", "UInt64", inverses, hex_width=16))
    out.append('"""The inverse of `5^p` modulo `2^64`, for `p` from one to twenty two."""\n\n')
    out.append(array("_DIV5_MAX", "UInt64", maxima))
    out.append('"""`UInt64.MAX // 5^p`, the largest product a multiple can produce."""\n\n')
    out.append(array("_CHEAT_DELTA", "UInt8", deltas))
    out.append('"""How many decimal digits a left shift of `k` bits adds, before the\ncutoff below takes one back off."""\n\n')
    out.append(array("_CHEAT_START", "UInt16", starts))
    out.append('"""Where the cutoff for a shift of `k` starts and ends in the digits."""\n\n')
    joined = "".join(f'    "{cutoff}",\n' for cutoff in cutoffs)
    out.append(f"comptime _CHEAT_DIGITS = String(\n{joined})\n")
    out.append('"""The decimal expansion of `5^k` for every shift, end to end."""\n')
    return "".join(out)


def generate() -> dict[str, str]:
    return {TABLES: tables_file()}


if __name__ == "__main__":
    print(generate()[TABLES][:2000])
