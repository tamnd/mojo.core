#!/usr/bin/env python3
"""Emit the Mojo source for `core.unicode` from the derivation in ucd.py.

Two files, and the split is the point of having a generator at all:

`core/unicode/data.mojo` is five arrays of numbers and nothing else. Every
range in every table, every case mapping, the fold orbits, the ASCII fold
shortcut and the Latin-1 bitmask, in one flat blob each. It is unreadable and
it is supposed to be, which is why nothing else lives in it.

`core/unicode/tables.mojo` is the two hundred and thirty six names Go exports
for those ranges, each one four numbers saying where in the blob its entries
are, plus the six functions that hand back Go's maps.

Everything else in the package is written by hand against these two. That is
deliberate: the part a generator produces should be data, and the part a human
reads should be code.

The derivation itself is `tools/gen/ucd.py` and it is checked against Go's own
tables rather than against a reading of the standard. See docs/testing.md.
"""

from __future__ import annotations

import functools
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from gen import ucd

DATA = "core/unicode/data.mojo"
TABLES = "core/unicode/tables.mojo"

# 21 bits holds U+10FFFF, so a range is three of them in one word and the
# whole of every table in this library is one array of 64-bit integers. The
# alternative was an array of structs, and a struct of three fields costs a
# byte of padding per entry and gives the compiler seven thousand aggregates
# to fold instead of seven thousand integers.
# What `mojo format` wraps code at. Docstrings are left alone above it; code is
# not, and generated code that the formatter would rewrite fails `format-check`.
WIDTH = 80

LO_BITS = 21
HI_SHIFT = 21
STRIDE_SHIFT = 42

DATA_HEADER = '''"""Every number in `core.unicode`, in five arrays.

Generated from the vendored Unicode character database by
`tools/gen/unicode.py`. Do not edit: change `tools/gen/ucd.py` and run
`pixi run gen`. `pixi run generated-check` fails on a diff.

Nothing here is public except the version. `letter.mojo` reads these and
`tables.mojo` says which part of `_RANGES` each of Go's named tables is, and
between them they are the whole audience for this file.

A range is packed into one 64-bit word as `lo | hi << {hi}` `| stride << {stride}`,
because U+10FFFF needs {lo} bits and three of those fit in a word with room
over. The tables are laid out end to end in one array rather than one array
each, so that a `RangeTable` can be four integers a caller can copy rather
than a pointer to something with a lifetime.

Reading one is `materialize[_RANGES]()[i]`, which is a load from read only
memory and not a copy of the array. `docs/design.md` section 6 has the
measurement, and if that ever stops being true this package gets very slow
rather than wrong.
"""
'''

TABLES_HEADER = '''"""Go's named Unicode tables, as offsets into `data.mojo`.

Generated by `tools/gen/unicode.py`. Do not edit: change `tools/gen/ucd.py`
and run `pixi run gen`. `pixi run generated-check` fails on a diff.

Every name Go exports as a `*RangeTable` is here under exactly Go's spelling,
including the underscores in `White_Space` and the capital in `Adlam`, because
a table is a variable and `tools/parity/rules.py` leaves a variable's name
alone. `Digit` really is the same table as `Nd` and is written as an alias of
it, which is what Go does too.

The six functions at the bottom are Go's six maps. They are functions rather
than variables because a `Dict` cannot be a compile time constant, so each one
builds its map when it is called. Calling `Categories()` in a loop allocates a
hundred times; hold the result, or reach for the named table directly, which
is what almost every caller wants anyway.
"""

from .letter import RangeTable

'''


@functools.cache
def blob() -> tuple[list[int], dict[str, tuple[int, int, int, int]], dict[str, dict[str, str]]]:
    """The packed ranges, where each table sits in them, and the names by group.

    Identical tables share their entries. `Sentence_Terminal` and its
    deprecated spelling `STerm` are the same set of code points, and so are
    `Digit` and `Nd`, and there is no reason to write either twice.
    """
    db = ucd.load()
    words: list[int] = []
    where: dict[str, tuple[int, int, int, int]] = {}
    seen: dict[tuple, tuple[int, int, int, int]] = {}

    def add(name: str, codes: list[int]) -> None:
        r16, r32, latin = ucd.runs(codes)
        key = (
            tuple((r.lo, r.hi, r.stride) for r in r16),
            tuple((r.lo, r.hi, r.stride) for r in r32),
        )
        if key in seen:
            where[name] = seen[key]
            return
        at = len(words)
        for run in list(r16) + list(r32):
            words.append(run.lo | (run.hi << HI_SHIFT) | (run.stride << STRIDE_SHIFT))
        seen[key] = where[name] = (at, len(r16), len(r32), latin)

    groups: dict[str, dict[str, str]] = {}

    groups["categories"] = {}
    for name in db.categories:
        add(name, ucd.in_category(db, name))
        groups["categories"][name] = name

    groups["scripts"] = {}
    for name in sorted(db.scripts):
        add(name, db.scripts[name])
        groups["scripts"][name] = name

    groups["properties"] = {}
    for name in sorted(db.props):
        add(name, db.props[name])
        groups["properties"][name] = name
    for long, short in ucd.DEPRECATED_ALIASES.items():
        where[short] = where[long]
        groups["properties"][short] = short

    groups["fold_category"] = {}
    for name in db.categories:
        found = ucd.fold_exceptions(db, ucd.in_category_for_folding(db, name))
        if found:
            add(f"_fold_{name}", found)
            groups["fold_category"][name] = f"_fold_{name}"

    groups["fold_script"] = {}
    for name in sorted(db.scripts):
        found = ucd.fold_exceptions(db, db.scripts[name])
        if found:
            add(f"_fold_{name}", found)
            groups["fold_script"][name] = f"_fold_{name}"

    return words, where, groups


# Go's eleven readable spellings of a category it also exports by its two
# letter name. Same table, second name, and a reader looking for `Letter` is
# not helped by being told to go and find `L`.
SPELLINGS = {
    "Digit": "Nd",
    "Letter": "L",
    "Lower": "Ll",
    "Mark": "M",
    "Number": "N",
    "Other": "C",
    "Punct": "P",
    "Space": "Z",
    "Symbol": "S",
    "Title": "Lt",
    "Upper": "Lu",
}

DESCRIBE = {
    "categories": "The `{name}` general category",
    "scripts": "The `{name}` script",
    "properties": "The `{name}` property",
    "fold_category": "The code points that fold into `{name}` from outside it",
    "fold_script": "The code points that fold into the `{name}` script from outside it",
}


def array(name: str, kind: str, values: list[int], hex_width: int = 0) -> str:
    """One `comptime` array, one value to a line.

    One to a line because `mojo format` explodes any collection with a
    trailing comma and packing them would produce a file that fails
    format-check the first time somebody ran the formatter over it.
    """
    if hex_width:
        rendered = [f"0x{v:0{hex_width}X}" for v in values]
    else:
        rendered = [str(v) for v in values]
    body = "".join(f"    {v},\n" for v in rendered)
    return f"comptime {name}: Array[{kind}, {len(values)}] = [\n{body}]\n"


def data_file() -> str:
    """`core/unicode/data.mojo`."""
    db = ucd.load()
    words, _, _ = blob()
    orbit = ucd.case_orbit(db)
    if not ucd.orbit_fits_16_bits(orbit):
        raise ValueError("a fold orbit has left the basic multilingual plane")

    cases = ucd.case_ranges(db)
    out = [
        DATA_HEADER.format(lo=LO_BITS, hi=HI_SHIFT, stride=STRIDE_SHIFT),
        "\n",
        f'comptime VERSION = "{ucd.version()}"\n',
        '"""The edition of the Unicode standard these tables are derived from.\n\n'
        "Go's `Version`. It is checked in as well as generated, so a reader can\n"
        "see which edition a build of this library answers for without running\n"
        'anything.\n"""\n',
        "\n",
        array("_RANGES", "UInt64", words, hex_width=16),
        '"""Every range in every table, `lo | hi << 21 | stride << 42`."""\n',
        "\n",
        f"comptime _CASE_COUNT = {len(cases)}\n",
        '"""How many case ranges there are, so `_CASES` is five times this."""\n',
        "\n",
        array("_CASES", "Int32", [n for c in cases for n in (c.lo, c.hi, *c.delta)]),
        '"""Go\'s `CaseRanges`, five numbers each: lo, hi, and the three deltas."""\n',
        "\n",
        f"comptime _ORBIT_COUNT = {len(orbit)}\n",
        '"""How many code points have a fold orbit."""\n',
        "\n",
        array("_ORBIT", "UInt32", [(a << 16) | b for a, b in orbit], hex_width=8),
        '"""Go\'s `caseOrbit`, `from << 16 | to`, sorted so a binary search works."""\n',
        "\n",
        array("_ASCII_FOLD", "UInt16", ucd.ascii_fold(db), hex_width=4),
        '"""`simple_fold` for the ASCII code points, so the common case is a load."""\n',
        "\n",
        array("_LATIN", "UInt8", ucd.latin1(db), hex_width=2),
        '"""The Latin-1 bitmask Go calls `properties`. `letter.mojo` names the bits."""\n',
    ]
    return "".join(out)


def tables_file() -> str:
    """`core/unicode/tables.mojo`."""
    words, where, groups = blob()
    del words
    out = [TABLES_HEADER]

    for group in ("categories", "scripts", "properties", "fold_category", "fold_script"):
        for go_name, mojo_name in groups[group].items():
            at, n16, n32, latin = where[mojo_name if group.startswith("fold") else go_name]
            out.append(f"comptime {mojo_name} = RangeTable({at}, {n16}, {n32}, {latin})\n")
            described = DESCRIBE[group].format(name=go_name)
            if group.startswith("fold"):
                out.append(f'"""{described}."""\n\n')
            else:
                out.append(f'"""{described}. Go\'s `unicode.{go_name}`."""\n\n')

    for spelling, table in SPELLINGS.items():
        out.append(f"comptime {spelling} = {table}\n")
        out.append(
            f'"""Another name for `{table}`, as Go has one. Go\'s `unicode.{spelling}`."""\n\n'
        )

    # Two blank lines before a `def`, which is what the formatter wants and
    # what the loop above, ending each entry with one, has not left.
    out.append("\n")
    out.append(_map("Categories", "the general categories", groups["categories"]))
    out.append(_map("Scripts", "the scripts", groups["scripts"]))
    out.append(_map("Properties", "the binary properties", groups["properties"]))
    out.append(
        _map(
            "FoldCategory",
            "the fold exceptions of each category",
            groups["fold_category"],
        )
    )
    out.append(
        _map("FoldScript", "the fold exceptions of each script", groups["fold_script"])
    )
    out.append(_aliases())
    return "".join(out)


def _map(name: str, what: str, entries: dict[str, str]) -> str:
    """One of Go's five `map[string]*RangeTable` variables, as a function."""
    lines = [
        f"def {name}() -> Dict[String, RangeTable]:\n",
        f'    """Go\'s `unicode.{name}`: {what}, by name.\n\n',
        f"    A new `Dict` on every call, with {len(entries)} entries. The named\n",
        "    tables above are the same data and cost nothing, so reach for one of\n",
        "    those unless the name is only known at run time.\n",
        '    """\n',
        "    var out = Dict[String, RangeTable]()\n",
    ]
    for go_name, mojo_name in entries.items():
        lines.append(_entry(f'"{go_name}"', mojo_name))
    lines.append("    return out^\n\n\n")
    return "".join(lines)


def _entry(key: str, value: str) -> str:
    """One `out[key] = value`, wrapped the way the formatter would wrap it.

    Generated output is checked in and `pixi run format-check` runs over it, so
    a line the formatter would rewrite is a failing build rather than a cosmetic
    difference. Only one entry in the whole file is long enough to matter,
    `Other_Default_Ignorable_Code_Point`, and this is the shape `mojo format`
    gives it.
    """
    line = f"    out[{key}] = {value}\n"
    if len(line) <= WIDTH + 1:
        return line
    return f"    out[\n        {key}\n    ] = {value}\n"


def _aliases() -> str:
    """Go's `CategoryAliases`, the long name of each general category."""
    db = ucd.load()
    lines = [
        "def CategoryAliases() -> Dict[String, String]:\n",
        '    """Go\'s `unicode.CategoryAliases`: `Uppercase_Letter` is `Lu`.\n\n',
        "    The long names Unicode gives the general categories, mapped to the\n",
        "    two letter ones the tables above are keyed by. Nothing in this\n",
        "    package reads it; it is here because a program taking a category\n",
        "    name from a user has to accept both spellings.\n",
        '    """\n',
        "    var out = Dict[String, String]()\n",
    ]
    for long in sorted(db.aliases):
        lines.append(_entry(f'"{long}"', f'"{db.aliases[long]}"'))
    lines.append("    return out^\n")
    return "".join(lines)


def generate() -> dict[str, str]:
    """The two generated files, ready to be written or diffed."""
    return {DATA: data_file(), TABLES: tables_file()}
