#!/usr/bin/env python3
"""Embed Mozilla's root certificate store as a table the tests can read.

Nothing in this library's test suite opens a file, for the reason
`tools/gen/jsonsuite.py` gives at length: the suite is one binary, it runs on
three platforms and under the sanitiser, and a test that reads a relative path
passes or fails depending on where the binary was started from. So the corpus
is turned into data here and the test reads the data.

The corpus is `tests/data/ca/cacert-2026-08-13.pem`, which is Mozilla's store
converted to PEM by curl's `mk-ca-bundle.pl` and served under a dated name so
that the digest in the lock file stays true. A hundred and twenty one
certificates, 129,143 bytes of DER between them, every one of them a real
document signed by a real authority that a browser trusts today.

That is the point of using it. A test table is written by whoever wrote the
code and tests what they thought of; a certificate authority bundle was written
by a hundred different programs over twenty five years and holds the string
types nobody chooses on purpose, the tag numbers nobody reaches for, and the
integers with a leading zero byte that a signature is computed over. If
`Parser` and `Builder` are inverse over this, they are inverse.

The bodies are kept as base64 rather than as hex, because that is the form the
file already holds them in and it is two thirds the size. They are decoded in
the fixture rather than here, by twenty lines written out in full, so that a
generated test fixture does not import half the library to read its own data
and then stop building for a reason that has nothing to do with what it tests.

The bodies go in one constant of a hundred and seventy thousand characters
rather than in a hundred and twenty one statements, and that shape is chosen
for the formatter. A bare assignment of a long string literal is the one thing
`mojo format` leaves exactly as it found it, which is why `tools/gen/tzif.py`
uses it and why `core/time/tzdata/data.mojo` is one line of four hundred and
sixty thousand characters. A comma separates them and base64 has no comma in
it.

The names cannot go the same way, because they have spaces in them and the
formatter breaks a long literal at a space into a column of joined pieces, so
the generated file would stop matching what this writes. They go one to a line
instead, in a list the formatter has nothing to do to, and `generate` refuses
a name too long to sit on a line by itself.

Nothing pins a digest here. It would be redundant: `vendor-check` holds the
bundle to the digest in the lock file, and `generated-check` regenerates this
from that same bundle and fails on a diff, so a file edited by hand is caught
twice before it reaches a test.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lib.tree import ROOT

OUT = "tests/generated/cabundle.mojo"
DATA = ROOT / "tests" / "data" / "ca" / "cacert-2026-08-13.pem"

# One entry of the bundle: the friendly name curl writes above the block, the
# row of equals signs under it, and the certificate itself.
ENTRY = re.compile(
    r"\n([^\n#][^\n]*)\n=+\n-----BEGIN CERTIFICATE-----\n(.*?)-----END CERTIFICATE-----",
    re.S,
)

HEADER = '''# Generated by tools/gen/cabundle.py from tests/data/ca/cacert-2026-08-13.pem.
#
# Certificate data from Mozilla, converted to PEM by curl's mk-ca-bundle.pl.
# Use of this data is governed by the Mozilla Public License 2.0, which is
# reproduced in full in third_party/cabundle/LICENSE.
#
# Do not edit. Change the generator or the corpus, and regenerate.

"""Mozilla's root certificate store, as data.

A hundred and twenty one root certificates, the set a browser trusts, in the
order the bundle lists them. Each one is the DER of a whole
`Certificate` as X.509 defines it, signature and all, which is
between four hundred and forty two and two thousand and seven bytes.

`tests/encoding/asn1/test_bundle.mojo` reads every one of them with `Parser`,
writes what it read back with `Builder`, and compares the two byte for byte.
DER exists so that two programs looking at the same object agree about its
bytes, and this is the only test that can say the pair here does.

The bodies are base64, which is the form the bundle already holds them in.
They are decoded below rather than by `core.encoding.base64`, because a
generated fixture that imports the library to read its own data is a fixture
that stops building for reasons unrelated to what it tests.
"""


def _sextet(digit: UInt8) -> UInt8:
    """The value of one base64 character.

    The standard alphabet, which is the only one a PEM file is written in.
    Nothing validates the input because nothing but this file supplies it.
    """
    if digit >= 0x41 and digit <= 0x5A:
        return digit - 0x41
    if digit >= 0x61 and digit <= 0x7A:
        return digit - 0x61 + 26
    if digit >= 0x30 and digit <= 0x39:
        return digit - 0x30 + 52
    if digit == 0x2B:
        return 62
    return 63


def _b64[o: ImmOrigin](text: StringSlice[o]) -> List[UInt8]:
    """The bytes that base64 spells.

    Four characters to three bytes, with `=` in the last one or two positions
    of the final group where the input did not divide evenly.
    """
    var raw = text.as_bytes()
    var out = List[UInt8](capacity=len(raw) // 4 * 3)
    var i = 0
    while i + 3 < len(raw):
        var a = _sextet(raw[i])
        var b = _sextet(raw[i + 1])
        out.append(a << 2 | b >> 4)
        if raw[i + 2] != UInt8(0x3D):
            var c = _sextet(raw[i + 2])
            out.append((b & 0x0F) << 4 | c >> 2)
            if raw[i + 3] != UInt8(0x3D):
                out.append((c & 0x03) << 6 | _sextet(raw[i + 3]))
        i += 4
    return out^


struct RootCertificate(Copyable, Movable):
    """One certificate of the bundle, under the name the bundle gives it."""

    var name: String
    """The friendly name, which is the subject as the converter wrote it."""

    var der: List[UInt8]
    """The certificate, byte for byte."""

    def __init__(out self, name: StringSlice, var der: List[UInt8]):
        self.name = String(name)
        self.der = der^


def root_certificates() -> List[RootCertificate]:
    """The whole bundle, in the order it lists them."""
    var names = _names()
    var bodies = _BODIES.split(",")
    var out = List[RootCertificate](capacity=len(names))
    for i in range(len(names)):
        out.append(RootCertificate(names[i], _b64(bodies[i])))
    return out^


def _names() -> List[String]:
    """Every friendly name, in the order `_BODIES` is in."""
    return [
{names}    ]
'''

TAIL = '''

comptime _BODIES = {bodies}
"""Every certificate, comma separated, as the base64 the bundle holds."""
'''


def generate() -> dict[str, str]:
    """The fixture, from the vendored bundle."""
    text = DATA.read_text()
    found = ENTRY.findall(text)
    if not found:
        raise ValueError(f"no certificates in {DATA}")

    names = []
    bodies = []
    for name, block in found:
        name = name.strip()
        if '"' in name or "\\" in name:
            raise ValueError(f"{name!r} would not survive being written as a literal")
        # One name to a line, and the formatter leaves a line it can already
        # fit alone. A longer one it would break in half at a space, and the
        # generated file would stop matching what the generator writes.
        if len(name) > 64:
            raise ValueError(f"{name!r} is too long to sit on a line of its own")
        names.append(name)
        bodies.append("".join(block.split()))

    body = HEADER.replace(
        "{names}", "".join(f'        "{name}",\n' for name in names)
    ) + TAIL.format(bodies='"' + ",".join(bodies) + '"')
    return {OUT: body}


if __name__ == "__main__":
    for path, contents in generate().items():
        (ROOT / path).write_text(contents)
        print(f"wrote {path}")
