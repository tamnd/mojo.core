#!/usr/bin/env python3
"""Turn Go's zoneinfo.zip into one Mojo source file holding the whole database.

Go's `time/tzdata` carries the IANA zone database inside the binary so that a
program can name a zone on a host that has none: a container built from
scratch, or Windows. This is where those bytes come from.

The source is Go's own `lib/time/zoneinfo.zip`, pinned by digest in
tests/data/LOCK.toml. Pinning Go's copy rather than a tzdata release is
deliberate. It means a disagreement between this library and Go about what a
zone did in 1943 is a disagreement about the code and not about which release
of the database each side happened to compile, and it is the same reason the
four TZif fixtures come from Go's testdata rather than from anywhere else.

Nothing is compressed. The zip holds 598 entries and 345,647 bytes, of which
231,108 bytes are distinct, because the aliases are whole copies: Etc/GMT and
its nine other spellings are ten identical files. Storing each distinct file
once and pointing the aliases at it takes a third off before anything clever
happens, and what is left is small enough that a deflate decoder would be a
dependency bought for nothing. There is no deflate decoder in this library yet
anyway.

The bytes go in as hex, one string, for the reason tools/gen/tzif.py gives:
an array would be a quarter of a million comptime elements and a string costs
the compiler nothing. A 800 KB comptime string compiles in about a second,
which was measured rather than hoped for.

The index is a second string of fixed width records, sorted by name, so the
lookup is a binary search into it with no parsing and no allocation. Each
record is a 32 byte name padded out to that width, six hex digits of offset
into the blob, and four hex digits of length. The padding keeps the sort order
because the byte it pads with is below every byte that appears in a zone name,
so `Etc/GMT` still sorts before `Etc/GMT+0`.

The padding byte is `!` and not a space, which would read better, because
`mojo format` breaks a long string literal at its spaces and this file has to
come out of the generator already formatted or `pixi run check` has two of its
steps demanding different bytes. A string with no spaces in it is left alone,
which is also why the blob is one long line.
"""

from __future__ import annotations

import hashlib
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lib.tree import ROOT

OUT = "core/time/tzdata/data.mojo"
ZIP = ROOT / "tests" / "data" / "go-time" / "zoneinfo.zip"

# The widths of the three fields of an index record. The name is the longest
# name in the database, America/Argentina/ComodRivadavia at 32. The offset is
# six digits for a blob of 231,108 bytes, which needs five, and the spare digit
# is there so that a database that grows past a megabyte does not change the
# shape of the file. The length is four for a largest file of 2,968 bytes.
NAME_WIDTH = 32
START_WIDTH = 6
LENGTH_WIDTH = 4

# What a name shorter than the field is padded out with. Below every byte a
# zone name is made of, which is what keeps the records in name order, and not
# a space, for the reason at the top of this file.
PAD = "!"

HEADER = '''# Generated by tools/gen/tzdata.py from tests/data/go-time/zoneinfo.zip.
#
# Copyright (c) 2009 The Go Authors. All rights reserved.
# Use of this source code is governed by a BSD style licence, which is
# reproduced in full in third_party/go/LICENSE.
#
# The zone database inside the archive is the IANA one, which its maintainers
# place in the public domain. See https://www.iana.org/time-zones.
#
# Do not edit. Change the generator or the archive, and regenerate.

"""The IANA zone database, compiled in.

Two strings and five numbers. `BLOB` is every distinct zone file in the
database, one after another, in hex. `INDEX` is one fixed width record per
name, sorted, holding the name and where in `BLOB` its file starts and how long
it is. `load_location` in this package is the only thing that reads either, and
it does a binary search over `INDEX` and decodes the one file it was asked for.

The files are stored once each rather than once per name. Most of the database
is aliases and an alias in the archive is a whole copy, so `Etc/GMT` and its
nine other spellings are ten identical files there and one file here with ten
records pointing at it.
"""
'''


def records(index: dict[str, tuple[int, int]]) -> str:
    """The index, one fixed width record per name, in name order."""
    out = []
    for name in sorted(index):
        start, length = index[name]
        out.append(name.ljust(NAME_WIDTH, PAD))
        out.append(f"{start:0{START_WIDTH}x}")
        out.append(f"{length:0{LENGTH_WIDTH}x}")
    return "".join(out)


def read() -> tuple[bytes, dict[str, tuple[int, int]]]:
    """The deduplicated blob and where each name lives in it."""
    blob = bytearray()
    at: dict[bytes, int] = {}
    index: dict[str, tuple[int, int]] = {}
    with zipfile.ZipFile(ZIP) as archive:
        for name in sorted(archive.namelist()):
            # Both of these are properties the lookup relies on rather than
            # checks, so they are checked here, once, where a database that
            # grew a name nobody expected fails the build instead of quietly
            # resolving to the wrong zone. A name holding a byte at or below
            # the padding would pad into the order of some other name, and
            # `Etc/GMT!` would pad to the same record as `Etc/GMT`.
            if len(name) > NAME_WIDTH:
                raise SystemExit(f"{name} is longer than {NAME_WIDTH} bytes")
            for c in name:
                # Above the padding, so the order holds, and printable ASCII,
                # so a character is a byte and the widths above are in bytes.
                if not PAD < c <= "~":
                    raise SystemExit(f"{name} holds {c!r}, which is not between {PAD!r} and '~'")
            data = archive.read(name)
            if data not in at:
                at[data] = len(blob)
                blob += data
            index[name] = (at[data], len(data))
    return bytes(blob), index


def generated() -> str:
    """The whole file."""
    blob, index = read()
    digest = hashlib.sha256(ZIP.read_bytes()).hexdigest()

    parts = [HEADER]
    parts.append(
        "\n".join(
            [
                f"comptime NAME_WIDTH = {NAME_WIDTH}",
                '"""How many bytes of a record the name takes, padded with `PAD`."""',
                "",
                f"comptime PAD = 0x{ord(PAD):02x}",
                '"""The byte a name shorter than `NAME_WIDTH` is padded out with.',
                "",
                "Below every byte a zone name is made of, so padding a short name does not",
                "move it in the order, and not a space, because `mojo format` would break",
                'this file at one and the generator has to write what the formatter would.',
                '"""',
                "",
                f"comptime START_WIDTH = {START_WIDTH}",
                '"""How many hex digits of a record say where the file starts."""',
                "",
                f"comptime LENGTH_WIDTH = {LENGTH_WIDTH}",
                '"""How many hex digits of a record say how long the file is."""',
                "",
                f"comptime RECORD = {NAME_WIDTH + START_WIDTH + LENGTH_WIDTH}",
                '"""The whole width of one record, which is the three above."""',
                "",
                f"comptime COUNT = {len(index)}",
                '"""How many names are in the index."""',
            ]
        )
    )
    parts.append(
        f'# sha256 {digest}, the archive this came from\n'
        f'comptime INDEX = "{records(index)}"\n'
        f'"""One record per name, sorted by name, {len(index)} of them."""'
    )
    parts.append(
        f'comptime BLOB = "{blob.hex()}"\n'
        f'"""Every distinct zone file, one after another, {len(blob)} bytes."""'
    )
    return "\n\n".join(parts) + "\n"


def generate() -> dict[str, str]:
    return {OUT: generated()}


if __name__ == "__main__":
    print(generate()[OUT][:2000])
