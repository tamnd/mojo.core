#!/usr/bin/env python3
"""Emit the ziggurat tables `core.math.rand` needs for its two distributions.

Six tables and two constants, none of which anybody should be reading. They are
the strip boundaries of the Marsaglia and Tsang ziggurat, one set for the
normal distribution and one for the exponential, and `norm_float64` and
`exp_float64` are the only readers.

Go writes all six out as literals in `normal.go` and `exp.go`, and then derives
them a second time in `rand_test.go` and checks the two against each other.
That test is the generator: `initNorm` and `initExp` are twenty lines of
arithmetic that reproduce every value bit for bit, and this is those twenty
lines in Python. Deriving rather than copying means the tables cannot be
mistyped, and the ported `test_norm_tables` and `test_exp_tables` still do what
Go's do, which is to derive them a third time at runtime and compare.

The float32 entries are written as the shortest decimal that reads back as the
same float32, which is the same rule Go's own source follows and is what makes
the generated file diffable against Go's.

Everything here is deterministic and depends on nothing outside Python.
"""

from __future__ import annotations

import math
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

TABLES = "core/math/rand/tables.mojo"

# Go's `rn` and `re`, the right hand edge of the base strip in each ziggurat.
# Written the way Go writes them as well as read as numbers, because Python's
# shortest form for the second one is `7.69711747013105`, which is the same
# float64 and a worse thing to diff against Go's source.
RN_SPELLING = "3.442619855899"
RE_SPELLING = "7.69711747013104972"
RN = float(RN_SPELLING)
RE = float(RE_SPELLING)

# Go's `vn` and `ve`, the area of one strip. These are the numbers the whole
# construction is solved for and they are not derivable from anything else
# here; Marsaglia and Tsang's paper is where they come from.
VN = 9.91256303526217e-3
VE = 3.9496598225815571993e-3

HEADER = '''"""The ziggurat tables, and nobody needs to read them.

Generated by `tools/gen/rand.py`. Do not edit: change the generator and run
`pixi run gen`. `pixi run generated-check` fails on a diff.

Nothing here is public. `normal.mojo` reads the first four and `exp.mojo` reads
the last four, and that is the whole audience.

The two distributions are sampled by the ziggurat method, which covers the
density with equal area strips and answers from a table lookup and one
comparison in the overwhelming majority of calls. `k` is the fraction of each
strip that can be accepted without evaluating the density at all, `w` scales an
integer into the strip, and `f` is the density at the strip's corner, which is
what the rare rejection test needs.

The `w` and `f` tables are `Float32` because Go's are, and that is not an
economy that can be quietly improved on: the rejection test is written in
single precision, so widening the tables changes which samples are accepted and
the stream stops matching Go's.
"""
'''


def f32(x: float) -> float:
    """`x` rounded to the nearest float32, still held as a Python float."""
    return struct.unpack("<f", struct.pack("<f", x))[0]


def literal(x: float) -> str:
    """The shortest decimal that reads back as this float32.

    Mojo parses a float literal at arbitrary precision and rounds once on the
    way into a `Float32`, so a decimal that identifies the value uniquely is
    exact. Seventeen digits is past the point where any float32 is ambiguous,
    so the loop always ends.
    """
    for digits in range(1, 18):
        said = f"{x:.{digits}g}"
        if f32(float(said)) == x:
            return said
    raise AssertionError(f"{x!r} has no round tripping decimal, which cannot happen")


def norm() -> tuple[list[int], list[float], list[float]]:
    """Go's `initNorm`, which is Go's `kn`, `wn` and `fn`.

    The walk runs downwards from strip 126, because each strip's boundary is
    solved from the one above it and the top one is where the tail starts.
    """
    m1 = 1 << 31
    dn = RN
    tn = dn
    kn = [0] * 128
    wn = [0.0] * 128
    fn = [0.0] * 128

    q = VN / math.exp(-0.5 * dn * dn)
    kn[0] = int((dn / q) * m1)
    kn[1] = 0
    wn[0] = f32(q / m1)
    wn[127] = f32(dn / m1)
    fn[0] = f32(1.0)
    fn[127] = f32(math.exp(-0.5 * dn * dn))
    for i in range(126, 0, -1):
        dn = math.sqrt(-2.0 * math.log(VN / dn + math.exp(-0.5 * dn * dn)))
        kn[i + 1] = int((dn / tn) * m1)
        tn = dn
        fn[i] = f32(math.exp(-0.5 * dn * dn))
        wn[i] = f32(dn / m1)
    return kn, wn, fn


def exp() -> tuple[list[int], list[float], list[float]]:
    """Go's `initExp`, which is Go's `ke`, `we` and `fe`.

    The same construction with 256 strips and no square root, since the
    exponential density is its own inverse in the way that matters here.
    """
    m2 = 1 << 32
    de = RE
    te = de
    ke = [0] * 256
    we = [0.0] * 256
    fe = [0.0] * 256

    q = VE / math.exp(-de)
    ke[0] = int((de / q) * m2)
    ke[1] = 0
    we[0] = f32(q / m2)
    we[255] = f32(de / m2)
    fe[0] = f32(1.0)
    fe[255] = f32(math.exp(-de))
    for i in range(254, 0, -1):
        de = -math.log(VE / de + math.exp(-de))
        ke[i + 1] = int((de / te) * m2)
        te = de
        fe[i] = f32(math.exp(-de))
        we[i] = f32(de / m2)
    return ke, we, fe


def array(name: str, kind: str, rendered: list[str]) -> str:
    """One `comptime` array, one value to a line.

    One to a line for the reason `tools/gen/strconv.py` does it: `mojo format`
    explodes any collection with a trailing comma, and generated code the
    formatter would rewrite fails `format-check` the first time anybody runs it.
    """
    body = "".join(f"    {v},\n" for v in rendered)
    return f"comptime {name}: Array[{kind}, {len(rendered)}] = [\n{body}]\n"


def tables_file() -> str:
    kn, wn, fn = norm()
    ke, we, fe = exp()

    out = [HEADER, "\n"]
    out.append(f"comptime _RN = {RN_SPELLING}\n")
    out.append(
        '"""Where the normal ziggurat\'s base strip ends. Go\'s `rn`."""\n\n'
    )
    out.append(array("_KN", "UInt32", [f"0x{v:08X}" for v in kn]))
    out.append(
        '"""How much of each normal strip is accepted outright. Go\'s `kn`."""\n\n'
    )
    out.append(array("_WN", "Float32", [literal(v) for v in wn]))
    out.append('"""The width of each normal strip. Go\'s `wn`."""\n\n')
    out.append(array("_FN", "Float32", [literal(v) for v in fn]))
    out.append('"""The density at each normal strip\'s corner. Go\'s `fn`."""\n\n')
    out.append(f"comptime _RE = {RE_SPELLING}\n")
    out.append(
        '"""Where the exponential ziggurat\'s base strip ends. Go\'s `re`."""\n\n'
    )
    out.append(array("_KE", "UInt32", [f"0x{v:08X}" for v in ke]))
    out.append(
        '"""How much of each exponential strip is accepted outright. Go\'s `ke`."""\n\n'
    )
    out.append(array("_WE", "Float32", [literal(v) for v in we]))
    out.append('"""The width of each exponential strip. Go\'s `we`."""\n\n')
    out.append(array("_FE", "Float32", [literal(v) for v in fe]))
    out.append('"""The density at each exponential strip\'s corner. Go\'s `fe`."""\n')
    return "".join(out)


def generate() -> dict[str, str]:
    return {TABLES: tables_file()}


if __name__ == "__main__":
    print(generate()[TABLES][:2000])
