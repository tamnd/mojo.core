#!/usr/bin/env python3
"""Embed the four vendored TZif files as byte tables the tests can read.

Nothing in this library's test suite opens a file. The suite is one binary and
it runs on three platforms and under the sanitiser, and a test that reads from
a relative path passes or fails depending on where the binary was started from,
which is not a property anybody wants to debug at eleven at night. So the
corpora are turned into data at generation time and the tests read the data.

The four files are Go's, vendored under `tests/data/go-time` and pinned by
digest in `tests/data/LOCK.toml`. They are small, 705 to 1496 bytes, which is
why embedding them is reasonable here and would not be for the Unicode tables.

Each file becomes one hex string rather than an array of byte literals. An
array would be the obvious shape and is the wrong one here: four of them is
close to four thousand comptime elements, the suite is already a fifty minute
compile under the sanitiser, and a string costs the compiler nothing. The test
side decodes with `bytes_of`, which is in the generated file so that the
decoding and the data cannot drift apart.

The digest of each file goes in a comment above its string, so that data edited
by hand rather than regenerated shows up as a digest that no longer matches
`LOCK.toml`.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lib.tree import ROOT

OUT = "tests/generated/tzif.mojo"
DATA = ROOT / "tests" / "data" / "go-time"

# The order the tables appear in, and the Mojo name each one gets. Go's own
# file names carry the tzdata release they came from, which is the thing worth
# keeping, so the names here are those with the release moved to the front.
FILES = [
    ("2020b_Europe_Berlin", "BERLIN_2020B"),
    ("2021a_America_Nuuk", "NUUK_2021A"),
    ("2021a_Asia_Gaza", "GAZA_2021A"),
    ("2021a_Europe_Dublin", "DUBLIN_2021A"),
]

HEADER = '''# Generated by tools/gen/tzif.py from tests/data/go-time.
#
# Copyright (c) 2009 The Go Authors. All rights reserved.
# Use of this source code is governed by a BSD style licence, which is
# reproduced in full in third_party/go/LICENSE.
#
# Do not edit. Change the generator or the corpus, and regenerate.

"""Go's four slim TZif files, as data.

A slim file is what tzdata has written since release 2020b: the explicit
transitions stop at the last one that was not predictable, and a POSIX TZ
string on the final line says what happens from there on. A fat file lists
every transition out to 2037 and has no TZ string. Both are still in the wild
and `core.time.tzif` reads both, but only a slim file exercises the join
between the table and the rule, which is where the bugs are.

Each string is the file byte for byte, in hex. The digest above it is the SHA256
that `tests/data/LOCK.toml` pins, so data edited rather than regenerated is
caught by `pixi run vendor-check` disagreeing with this file. `bytes_of` turns
one back into the bytes the reader wants.
"""


def bytes_of(hex: StringSlice) -> List[UInt8]:
    """The bytes a hex string spells.

    Two characters to a byte, lower case, no separators, which is the only form
    anything in this file is written in. Nothing validates the input because
    nothing but this file supplies it.
    """
    var raw = hex.as_bytes()
    var out = List[UInt8](capacity=len(raw) // 2)
    for i in range(0, len(raw) - 1, 2):
        out.append((_nibble(raw[i]) << 4) | _nibble(raw[i + 1]))
    return out^


def _nibble(c: UInt8) -> UInt8:
    """The value of one hex digit."""
    if c >= UInt8(ord("a")):
        return c - UInt8(ord("a")) + 10
    return c - UInt8(ord("0"))
'''


def table(name: str, data: bytes, digest: str, note: str) -> str:
    """One `comptime` hex string holding a whole file."""
    out = [f"# sha256 {digest}, {len(data)} bytes"]
    out.append(f'comptime {name} = "{data.hex()}"')
    out.append(f'"""{note}"""')
    return "\n".join(out)


NOTES = {
    "BERLIN_2020B": (
        "Europe/Berlin from tzdata 2020b, the release that introduced slim "
        "files. The ordinary case: explicit transitions to 1996 and a rule "
        "for everything after."
    ),
    "NUUK_2021A": (
        "America/Nuuk from tzdata 2021a. Greenland's daylight change is at an "
        "hour the TZ string can only write with a negative offset, which is "
        "the row `_tzset_offset` accepts a minus sign for."
    ),
    "GAZA_2021A": (
        "Asia/Gaza from tzdata 2021a. Its rules change often enough that the "
        "file carries explicit transitions well past the point most files "
        "stop, so the table and the trailing rule have to agree at the join."
    ),
    "DUBLIN_2021A": (
        "Europe/Dublin from tzdata 2021a. The one location whose daylight "
        "flag runs backwards: Irish Standard Time in summer is the standard "
        "clock and GMT in winter is the saving one, so `is_dst` is false in "
        "July and true in January."
    ),
}


def generated() -> str:
    """The whole file."""
    parts = [HEADER]
    for filename, name in FILES:
        data = (DATA / filename).read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        parts.append(table(name, data, digest, NOTES[name]))
    return "\n\n".join(parts) + "\n"


def generate() -> dict[str, str]:
    return {OUT: generated()}


if __name__ == "__main__":
    print(generate()[OUT][:2000])
