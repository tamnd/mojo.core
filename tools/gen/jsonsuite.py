#!/usr/bin/env python3
"""Embed JSONTestSuite's parsing corpus as a table the tests can read.

Nothing in this library's test suite opens a file. The suite is one binary and
it runs on three platforms and under the sanitiser, and a test that reads from
a relative path passes or fails depending on where the binary was started from,
which is not a property anybody wants to debug at eleven at night. So the
corpus is turned into data at generation time and the test reads the data.

Three hundred and eighteen files, vendored under `tests/data/jsontestsuite`
and pinned one by one in `tests/data/LOCK.toml`. Together they are 354,024
bytes, which sounds like far too much to embed until you notice that two files
are 350,001 of it: one is an opening bracket a hundred thousand times over and
the other is the same five characters fifty thousand times with a newline on
the end. Both are written out here as a unit and a count, so what this
generates carries 4,023 bytes of actual corpus.

The repeat is found rather than declared. Any file that turns out to be one
short run of bytes repeated at least a thousand times is emitted that way,
which means a corpus that grows another such file needs no edit here.

The whole table is two long string constants rather than three hundred and
eighteen statements, and that shape is chosen for the formatter. `mojo format`
runs over `tests/` and splits any call whose line is too long, and a document
here reaches three hundred characters of hex, so a table of calls would come
out of the generator one way and out of the formatter another and the two
checks that guard generated code would disagree forever. A bare assignment of a
long string literal is the one thing the formatter leaves exactly as it found
it, which is why `tools/gen/tzif.py` uses it and why `core/time/tzdata/data.mojo`
is one line of four hundred and sixty thousand characters.

Hex, rather than an array of byte literals or a string of the bytes themselves.
An array would be thousands of comptime elements, and a string literal cannot
hold what a third of this corpus holds, since the files that are not valid
UTF-8 are the point of those files.

Nothing pins a digest in the generated file, unlike the four TZif tables. It
would be redundant: `vendor-check` holds the corpus to the digests in the lock
file, and `generated-check` regenerates this from that same corpus and fails on
a diff, so a file edited by hand is caught twice before it reaches a test.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lib.tree import ROOT

OUT = "tests/generated/jsonsuite.mojo"
DATA = ROOT / "tests" / "data" / "jsontestsuite"

# Below this many repetitions a file is written out literally. A thousand is
# well past anything that could happen by accident in a corpus whose median
# file is eleven bytes.
MIN_REPEATS = 1000

# The widest unit a repeat is looked for at. The two files that need this have
# units of one byte and of five.
MAX_UNIT = 64

HEADER = '''# Generated by tools/gen/jsonsuite.py from tests/data/jsontestsuite.
#
# Copyright (c) 2016 Nicolas Seriot
# Use of this source code is governed by the MIT licence, which is reproduced
# in full in third_party/jsontestsuite/LICENSE.
#
# Do not edit. Change the generator or the corpus, and regenerate.

"""JSONTestSuite's parsing corpus, as data.

Nicolas Seriot's corpus from the article "Parsing JSON is a Minefield", which
is the closest thing there is to a conformance suite for RFC 8259. Three
hundred and eighteen documents, and the first letter of a name is the verdict:
`y_` has to be accepted, `n_` has to be refused, and `i_` is a case the
standard leaves open, where an implementation may do either so long as it
decides on purpose.

`tests/encoding/json/test_suite.mojo` runs `valid` over every one of them and
writes out the answer for each `i_` case by hand.

Two constants hold the whole corpus, one line each, because a bare assignment
of a long string literal is the one shape `mojo format` leaves alone and a
table of three hundred calls is not. A document is hex because a good third of
these files are deliberately not valid UTF-8 and a string literal cannot hold
them. Two of them are a short unit repeated a hundred thousand and fifty
thousand times, and those two are written as a unit, a count and a tail.
"""


def _nibble(digit: UInt8) -> UInt8:
    """The value of one lower case hex digit."""
    return digit - 0x30 if digit <= 0x39 else digit - 0x57


def _hex[o: ImmOrigin](text: StringSlice[o]) -> List[UInt8]:
    """The bytes those hex digits are.

    Two characters to a byte, lower case, no separators, which is the only form
    anything in this file is written in. Nothing validates the input because
    nothing but this file supplies it.
    """
    var raw = text.as_bytes()
    var out = List[UInt8](capacity=len(raw) // 2)
    for i in range(0, len(raw), 2):
        out.append(_nibble(raw[i]) << 4 | _nibble(raw[i + 1]))
    return out^


def _count[o: ImmOrigin](text: StringSlice[o]) -> Int:
    """The number those decimal digits spell.

    Written out rather than borrowed from `core.strconv`, because a generated
    test fixture that imports half the library to read its own data is a
    fixture that stops building for reasons unrelated to what it tests.
    """
    var raw = text.as_bytes()
    var value = 0
    for i in range(len(raw)):
        value = value * 10 + Int(raw[i] - 0x30)
    return value


def _document[o: ImmOrigin](spec: StringSlice[o]) -> List[UInt8]:
    """One document from its entry in `_DOCUMENTS`.

    An entry is hex, or hex and a `*` and a repeat count, or those and a `+`
    and a tail in hex. Only two of the three hundred and eighteen are anything
    but the first form.
    """
    var raw = spec.as_bytes()
    var star = -1
    var plus = -1
    for i in range(len(raw)):
        if raw[i] == UInt8(ord("*")):
            star = i
        elif raw[i] == UInt8(ord("+")):
            plus = i
    if star < 0:
        return _hex(spec)
    var stop = plus if plus >= 0 else len(raw)
    var unit = _hex(spec[byte=0:star])
    var times = _count(spec[byte = star + 1 : stop])
    var tail = _hex(spec[byte = stop + 1 :]) if plus >= 0 else List[UInt8]()
    var out = List[UInt8](capacity=len(unit) * times + len(tail))
    for _ in range(times):
        out.extend(unit.copy())
    out.extend(tail^)
    return out^


struct SuiteCase(Copyable, Movable):
    """One file from the corpus, under the name it has on disk."""

    var name: String
    """The file name, whose first letter is the verdict."""

    var document: List[UInt8]
    """The file, byte for byte."""

    def __init__(out self, name: StringSlice, var document: List[UInt8]):
        self.name = String(name)
        self.document = document^


def suite_cases() -> List[SuiteCase]:
    """The whole corpus, in file name order, which is also verdict order."""
    var names = _NAMES.split(",")
    var documents = _DOCUMENTS.split(",")
    var out = List[SuiteCase](capacity=len(names))
    for i in range(len(names)):
        out.append(SuiteCase(names[i], _document(documents[i])))
    return out^
'''


def as_repeat(data: bytes) -> tuple[bytes, int, bytes] | None:
    """`(unit, times, tail)` if `data` is one short run repeated, else nothing.

    The narrowest unit wins, so the hundred thousand brackets come out as one
    bracket a hundred thousand times rather than two brackets fifty thousand
    times, and a file that is not built this way falls through every width and
    is written out whole.
    """
    for width in range(1, MAX_UNIT + 1):
        if len(data) < width * MIN_REPEATS:
            return None
        unit = data[:width]
        times = 0
        while data[times * width : (times + 1) * width] == unit:
            times += 1
        if times >= MIN_REPEATS:
            return unit, times, data[times * width :]
    return None


def spec(data: bytes) -> str:
    """One document's entry in `_DOCUMENTS`."""
    repeat = as_repeat(data)
    if repeat is None:
        return data.hex()
    unit, times, tail = repeat
    if not tail:
        return f"{unit.hex()}*{times}"
    return f"{unit.hex()}*{times}+{tail.hex()}"


def generated() -> str:
    """The whole file."""
    names = sorted(p.name for p in DATA.iterdir() if p.is_file())
    for name in names:
        if "," in name:
            raise ValueError(f"a comma in a file name would split the table: {name!r}")
    specs = [spec((DATA / name).read_bytes()) for name in names]
    parts = [
        HEADER,
        "",
        'comptime _NAMES = "' + ",".join(names) + '"',
        '"""Every file name, comma separated, in the order `_DOCUMENTS` is in."""',
        "",
        'comptime _DOCUMENTS = "' + ",".join(specs) + '"',
        '"""Every document, comma separated. Hex, or hex and a `*` and a repeat\n'
        "count, or those and a `+` and a tail in hex.\"\"\"",
    ]
    return "\n".join(parts) + "\n"


def generate() -> dict[str, str]:
    return {OUT: generated()}


if __name__ == "__main__":
    print(generate()[OUT][:3000])
